#!/usr/bin/env python3
"""Generate docs/recompilation/environment.md from launcher/flags_catalog.h.

The catalog has one row per M2_*/IMSA_* environment variable the host, runtime,
or launcher reads: name, group, and description. This script renders it as the
reference page, grouped in catalog order.

Usage:
    python3 tools/gen_env_reference.py            # rewrite the page
    python3 tools/gen_env_reference.py --check    # exit 1 if the page is stale
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
CATALOG = REPO / "launcher" / "flags_catalog.h"
PAGE = REPO / "docs" / "recompilation" / "environment.md"
ROW = re.compile(r'\{"([A-Z0-9_]+)", "([^"]+)", "((?:[^"\\]|\\.)*)"\}')

INTRO = """\
# Environment Variables

<!-- Generated by tools/gen_env_reference.py from launcher/flags_catalog.h.
     Edit the catalog, then rerun the script. -->

`m2host`, the guest runtime, and the launcher read the `M2_*` and `IMSA_*`
environment variables below. Most are developer diagnostics: each stays off
unless set, and tracing output is bounded by a per-stream cap. The launcher
sets several of the user-facing settings (game data, saves, fixes, presentation)
from its tabs.

Conventions used below:

- A boolean switch is on when set to a nonempty value other than `0`, unless
  its description specifies `=1` or "When set to 1".
- "Default-on" entries are already active; set them to `0` to compare against
  the alternative each description names.
- `_FROM` variables set a starting frame or list sequence number, and `_MAX` or
  `_N` variables raise a trace's line cap. Values accept decimal or `0x` hex.
- Host frames count presented frames; guest frames count the game's own frame
  loop; list sequence numbers count executed command lists.

See [Diagnostics](../../AGENTS.md#diagnostics) for the trace file, control socket, and
recording tools these switches complement.
"""


def load_rows():
    rows = ROW.findall(CATALOG.read_text(encoding="utf-8"))
    if not rows:
        raise SystemExit(f"no catalog rows found in {CATALOG}")
    return [(n, g, d.replace('\\"', '"')) for n, g, d in rows]


def render(rows) -> str:
    groups: dict[str, list[tuple[str, str]]] = {}
    for name, group, desc in rows:
        groups.setdefault(group, []).append((name, desc))
    out = [INTRO]
    for group, entries in groups.items():
        out.append(f"\n## {group}\n\n| Variable | Description |\n| --- | --- |\n")
        for name, desc in entries:
            # Escape for a GFM table cell, then restore comparison operators:
            # only angle-bracket tokens such as `ra_<track>` need entity form.
            cell = (desc.replace("|", "\\|").replace("<", "&lt;")
                    .replace(">", "&gt;"))
            for op in ("->", ">=", "<=", "=>", "=<"):
                cell = cell.replace(op.replace("<", "&lt;").replace(">", "&gt;"), op)
            out.append(f"| `{name}` | {cell} |\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="report a stale page instead of rewriting it")
    args = ap.parse_args()
    text = render(load_rows())
    if args.check:
        current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if current != text:
            print(f"{PAGE.relative_to(REPO)} is stale; run "
                  "python3 tools/gen_env_reference.py", file=sys.stderr)
            return 1
        return 0
    with open(PAGE, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
